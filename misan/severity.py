"""Severity estimation: continuous index, three-level label and trend (PRD FR-13, FR-15)."""
from __future__ import annotations

from collections import defaultdict, deque

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor

from misan.features import FEATURE_COLUMNS


def severity_label(index: float) -> str:
    if index < 1 / 3:
        return "low"
    if index < 2 / 3:
        return "medium"
    return "high"


class SeverityModel:
    """Regresses the known simulated severity parameter (0-1). Only meaningful once
    trained on severity-labelled data generated by `misan.simulate` — the MVP does not
    claim severity estimation works before that training has actually happened."""

    def __init__(self, n_estimators: int = 300, random_state: int = 42):
        self.model = RandomForestRegressor(n_estimators=n_estimators, random_state=random_state, n_jobs=-1)
        self.feature_columns: list[str] = FEATURE_COLUMNS
        self.is_trained = False

    def fit(self, X: pd.DataFrame, y_severity: pd.Series) -> None:
        self.model.fit(X[self.feature_columns], y_severity)
        self.is_trained = True

    def predict(self, X: pd.DataFrame) -> np.ndarray:
        if not self.is_trained:
            raise RuntimeError("severity model has not been trained")
        return np.clip(self.model.predict(X[self.feature_columns]), 0.0, 1.0)

    def save(self, path: str) -> None:
        joblib.dump(self, path)

    @staticmethod
    def load(path: str) -> "SeverityModel":
        return joblib.load(path)


class SeverityTrendTracker:
    """Tracks recent severity indices per asset to derive a simple trend (FR-15).

    In-memory per process, same documented limitation as `PersistenceTracker`.
    """

    def __init__(self, window: int = 4, flat_tolerance: float = 0.05):
        self.window = window
        self.flat_tolerance = flat_tolerance
        self._history: dict[str, deque[float]] = defaultdict(lambda: deque(maxlen=self.window))

    def update(self, asset_id: str, severity_index: float) -> str:
        history = self._history[asset_id]
        history.append(severity_index)
        if len(history) < 2:
            return "unknown"
        delta = history[-1] - history[0]
        if abs(delta) <= self.flat_tolerance:
            return "stable"
        return "rising" if delta > 0 else "falling"
